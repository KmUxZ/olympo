import { readFileSync, writeFileSync } from 'node:fs';
const BASE = 'http://127.0.0.1:4100';
const pass = /cuentas\): (\S+)/.exec(readFileSync(process.argv[2], 'utf8'))[1];
let f = 0; const check = (n, c, x = '') => { console.log(`${c ? 'OK  ' : 'FAIL'} ${n} ${c ? '' : JSON.stringify(x).slice(0, 400)}`); if (!c) f++; };
const login = async (client) => { const r = await fetch(BASE + '/api/auth/login', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ email: 'vendedora1@demo.olympo.test', password: pass, client }) }); return { cookie: r.headers.get('set-cookie')?.split(';')[0], json: await r.json() }; };
const web = (await login('web')).cookie;
const get = (p) => fetch(BASE + p, { headers: { cookie: web } });
let s = await (await get('/api/argos/extension/status')).json();
check('antes de instalar: no conectada', s.connected === false && s.serverUrl === 'https://olympo-prueba.onrender.com' && /^\d+\.\d+\.\d+$/.test(s.version), s);
check('sin sesión no se descarga', (await fetch(BASE + '/api/argos/extension.zip')).status === 401);
const r = await get('/api/argos/extension.zip');
const buf = Buffer.from(await r.arrayBuffer());
check('descarga como archivo ZIP llamado Argos.zip', r.status === 200 && r.headers.get('content-type') === 'application/zip' && r.headers.get('content-disposition').includes('Argos.zip') && buf.readUInt32LE(0) === 0x04034b50, [r.status, r.headers.get('content-type')]);
writeFileSync(process.argv[2].replace('credenciales-demo.txt', 'Argos.zip'), buf);
const ext = await login('extension');
check('la extensión inicia sesión', Boolean(ext.json.token), ext.json);
s = await (await get('/api/argos/extension/status')).json();
check('después de iniciar sesión en la extensión: conectada', s.connected === true, s);
console.log(f ? `\n${f} FALLOS` : '\nTODO OK'); process.exit(f ? 1 : 0);
